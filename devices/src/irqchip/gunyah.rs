/// GICv3 message-based interrupts (`--mbi-spis`). Gunyah takes a VM's irqfds from the device tree
/// it hands the resource manager at VM start, so a line added later never fires. The MBI SPIs get
/// their lines up front instead; a device's MSI vector, enabled by the guest at run time, is an
/// event the irq handler thread waits on (`service_irq_event`), and its route -- the message the
/// guest wrote, data = INTID -- picks the SPI line it raises.
struct Mbi {
    base_spi: u32,
    doorbell: u64,
    /// The line of each MBI SPI.
    spis: Vec<Event>,
    /// MSI vectors, indexed by the `IrqEventIndex` handed out for them: (gsi, event, SPI offset).
    vectors: Vec<Option<(u32, Event, Option<usize>)>>,
}

pub struct GunyahIrqChip {
    vm: GunyahVm,
    mbi: Arc<sync::Mutex<Option<Mbi>>>,
}

impl GunyahIrqChip {
    pub fn new(vm: GunyahVm) -> Result<GunyahIrqChip> {
        // NOTE: Unlike the other hypervisors supported by crosvm, the Gunyah IRQ chip is not
        // explicitly configured here. Instead, Gunyah uses the information in the FDT generated by
        // crosvm and to determine where and how to setup the IRQ chip.
        Ok(GunyahIrqChip {
            vm,
            mbi: Arc::new(sync::Mutex::new(None)),
        })
    }
}

impl IrqChip for GunyahIrqChip {
    // GunyahIrqChip doesn't need to track VCPUs.
    fn add_vcpu(&mut self, _vcpu_id: usize, _vcpu: &dyn Vcpu) -> Result<()> {
        Ok(())
    }

    fn register_edge_irq_event(
        &mut self,
        irq: u32,
        irq_event: &IrqEdgeEvent,
        _source: IrqEventSource,
    ) -> Result<Option<IrqEventIndex>> {
        if let Some(mbi) = self.mbi.lock().as_mut() {
            // An MSI vector: the irq handler thread waits on it and relays it to its route's SPI.
            let vector = Some((irq, irq_event.get_trigger().try_clone()?, None));
            let index = match mbi.vectors.iter().position(Option::is_none) {
                Some(index) => {
                    mbi.vectors[index] = vector;
                    index
                }
                None => {
                    mbi.vectors.push(vector);
                    mbi.vectors.len() - 1
                }
            };
            return Ok(Some(index));
        }
        self.vm
            .register_irqfd(irq, irq_event.get_trigger(), false)?;
        Ok(None)
    }

    fn unregister_edge_irq_event(&mut self, irq: u32, irq_event: &IrqEdgeEvent) -> Result<()> {
        if let Some(mbi) = self.mbi.lock().as_mut() {
            for vector in mbi.vectors.iter_mut() {
                if matches!(vector, Some((gsi, _, _)) if *gsi == irq) {
                    *vector = None;
                    return Ok(());
                }
            }
        }
        self.vm.unregister_irqfd(irq, irq_event.get_trigger())?;
        Ok(())
    }

    fn register_level_irq_event(
        &mut self,
        irq: u32,
        irq_event: &IrqLevelEvent,
        _source: IrqEventSource,
    ) -> Result<Option<IrqEventIndex>> {
        self.vm.register_irqfd(irq, irq_event.get_trigger(), true)?;
        Ok(None)
    }

    fn unregister_level_irq_event(&mut self, irq: u32, irq_event: &IrqLevelEvent) -> Result<()> {
        self.vm.unregister_irqfd(irq, irq_event.get_trigger())?;
        Ok(())
    }

    fn route_irq(&mut self, route: IrqRoute) -> Result<()> {
        let mut mbi = self.mbi.lock();
        let Some(mbi) = mbi.as_mut() else {
            return Err(base::Error::new(libc::ENOTSUP));
        };
        let IrqSource::Msi { address, data } = route.source else {
            return Ok(());
        };
        let spi = data.checked_sub(32 + mbi.base_spi).map(|spi| spi as usize);
        let spi = match spi {
            Some(spi) if address == mbi.doorbell && spi < mbi.spis.len() => Some(spi),
            _ => {
                warn!(
                    "MBI: gsi {} message {:#x}/{:#x} is not an MBI SPI, dropped",
                    route.gsi, address, data
                );
                None
            }
        };
        for (gsi, _, target) in mbi.vectors.iter_mut().flatten() {
            if *gsi == route.gsi {
                *target = spi;
            }
        }
        Ok(())
    }

    fn set_irq_routes(&mut self, routes: &[IrqRoute]) -> Result<()> {
        for route in routes {
            self.route_irq(*route)?;
        }
        Ok(())
    }

    /// Return a vector of all registered irq numbers and their associated events and event
    /// indices. These should be used by the main thread to wait for irq events.
    /// For the GunyahIrqChip, the kernel handles listening to irq events being triggered by
    /// devices, so this function always returns an empty Vec.
    fn irq_event_tokens(&self) -> Result<Vec<(IrqEventIndex, IrqEventSource, Event)>> {
        Ok(Vec::new())
    }

    fn service_irq(&mut self, _irq: u32, _level: bool) -> Result<()> {
        unimplemented!()
    }

    /// Service an IRQ event by asserting then deasserting an IRQ line. The associated Event
    /// that triggered the irq event will be read from. If the irq is associated with a resample
    /// Event, then the deassert will only happen after an EOI is broadcast for a vector
    /// associated with the irq line.
    /// On GunyahIrqChip only MSI vectors (--mbi-spis) are waited on: relay one to its SPI.
    fn service_irq_event(&mut self, event_index: IrqEventIndex) -> Result<()> {
        let mbi = self.mbi.lock();
        let Some(mbi) = mbi.as_ref() else {
            return Ok(());
        };
        if let Some(Some((_, event, target))) = mbi.vectors.get(event_index) {
            event.wait()?;
            if let Some(spi) = target {
                mbi.spis[*spi].signal()?;
            }
        }
        Ok(())
    }

    /// Broadcast an end of interrupt.
    /// This should never be called on a GunyahIrqChip because a Gunyah vcpu should never exit
    /// with VcpuExit::IoapicEoi.
    fn broadcast_eoi(&self, _vector: u8) -> Result<()> {
        unreachable!();
    }

    /// Injects any pending interrupts for `vcpu`.
    /// For GunyahIrqChip this is a no-op because Gunyah is responsible for injecting all
    /// interrupts.
    fn inject_interrupts(&self, _vcpu: &dyn Vcpu) -> Result<()> {
        Ok(())
    }

    /// Notifies the irq chip that the specified VCPU has executed a halt instruction.
    /// For GunyahIrqChip this is a no-op because Gunyah handles VCPU blocking.
    fn halted(&self, _vcpu_id: usize) {}

    fn wait_until_runnable(&self, _vcpu: &dyn Vcpu) -> Result<VcpuRunState> {
        // Gunyah handles vCPU blocking. From userspace perspective, vCPU is always runnable.
        Ok(VcpuRunState::Runnable)
    }

    /// Makes unrunnable VCPUs return immediately from `wait_until_runnable`.
    /// For GunyahIrqChip this is a no-op because Gunyah handles VCPU blocking.
    fn kick_halted_vcpus(&self) {}

    fn get_mp_state(&self, _vcpu_id: usize) -> Result<MPState> {
        unimplemented!()
    }

    fn set_mp_state(&mut self, _vcpu_id: usize, _state: &MPState) -> Result<()> {
        unimplemented!()
    }

    fn try_clone(&self) -> Result<Self>
    where
        Self: Sized,
    {
        Ok(Self {
            vm: self.vm.try_clone()?,
            mbi: self.mbi.clone(),
        })
    }

    fn finalize_devices(
        &mut self,
        _resources: &mut resources::SystemAllocator,
        _io_bus: &crate::Bus,
        _mmio_bus: &crate::Bus,
    ) -> Result<()> {
        Ok(())
    }

    /// The GunyahIrqChip doesn't process irq events itself so this function does nothing.
    fn process_delayed_irq_events(&mut self) -> Result<()> {
        Ok(())
    }

    fn irq_delayed_event_token(&self) -> Result<Option<Event>> {
        Ok(None)
    }

    fn check_capability(&self, _c: IrqChipCap) -> bool {
        false
    }
}

#[cfg(any(target_arch = "arm", target_arch = "aarch64"))]
impl IrqChipAArch64 for GunyahIrqChip {
    fn try_box_clone(&self) -> Result<Box<dyn IrqChipAArch64>> {
        Ok(Box::new(self.try_clone()?))
    }

    fn as_irq_chip(&self) -> &dyn IrqChip {
        self
    }

    fn as_irq_chip_mut(&mut self) -> &mut dyn IrqChip {
        self
    }

    fn get_vgic_version(&self) -> DeviceKind {
        DeviceKind::ArmVgicV3
    }

    fn finalize(&self) -> Result<()> {
        Ok(())
    }

    fn enable_mbi(&mut self, base_spi: u32, count: u32, doorbell: u64) -> Result<Vec<Event>> {
        let mut spis = Vec::new();
        for spi in base_spi..base_spi + count {
            let event = Event::new()?;
            self.vm.register_irqfd(spi, &event, false)?;
            spis.push(event);
        }
        let frame = spis.iter().map(Event::try_clone).collect::<Result<Vec<_>>>()?;
        *self.mbi.lock() = Some(Mbi {
            base_spi,
            doorbell,
            spis,
            vectors: Vec::new(),
        });
        Ok(frame)
    }

    fn mbi_route_event(&self, gsi: u32) -> Option<Event> {
        let mbi = self.mbi.lock();
        let mbi = mbi.as_ref()?;
        let spi = mbi.vectors.iter().flatten().find(|(g, _, _)| *g == gsi)?.2?;
        mbi.spis[spi].try_clone().ok()
    }
}
